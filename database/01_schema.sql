-- Run as TOEIC_OWNER on Oracle Database 19c. No existing objects are dropped.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF
CREATE TABLE toeic_roles (
 role_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 code VARCHAR2(30) NOT NULL UNIQUE, name VARCHAR2(100 CHAR) NOT NULL
) TABLESPACE toeic_data;
CREATE TABLE toeic_users (
 user_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 role_id NUMBER(12) NOT NULL REFERENCES toeic_roles(role_id),
 username VARCHAR2(40) NOT NULL UNIQUE, email VARCHAR2(150) NOT NULL UNIQUE,
 password_hash VARCHAR2(500) NOT NULL, full_name VARCHAR2(120 CHAR) NOT NULL,
 target_score NUMBER(3) DEFAULT 650 NOT NULL CHECK(target_score BETWEEN 10 AND 990),
 active NUMBER(1) DEFAULT 1 NOT NULL CHECK(active IN (0,1)),
 created_at TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
) TABLESPACE toeic_data;
CREATE TABLE toeic_groups (
 group_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 part_no NUMBER(1) NOT NULL CHECK(part_no BETWEEN 1 AND 7), title VARCHAR2(200 CHAR) NOT NULL,
 passage CLOB, audio_url VARCHAR2(1000), image_url VARCHAR2(1000)
) TABLESPACE toeic_data;
CREATE TABLE toeic_questions (
 question_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 group_id NUMBER(12) NOT NULL REFERENCES toeic_groups(group_id),
 prompt CLOB NOT NULL, explanation CLOB, correct_choice CHAR(1) NOT NULL CHECK(correct_choice IN ('A','B','C','D')),
 difficulty VARCHAR2(10) DEFAULT 'MEDIUM' NOT NULL CHECK(difficulty IN ('EASY','MEDIUM','HARD')),
 active NUMBER(1) DEFAULT 1 NOT NULL CHECK(active IN (0,1)),
 created_at TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
) TABLESPACE toeic_data;
CREATE TABLE toeic_choices (
 choice_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 question_id NUMBER(12) NOT NULL REFERENCES toeic_questions(question_id) ON DELETE CASCADE,
 choice_key CHAR(1) NOT NULL CHECK(choice_key IN ('A','B','C','D')), choice_text VARCHAR2(2000 CHAR) NOT NULL,
 CONSTRAINT uq_toeic_choice UNIQUE(question_id,choice_key)
) TABLESPACE toeic_data;
CREATE TABLE toeic_exams (
 exam_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 slug VARCHAR2(100) NOT NULL UNIQUE, title VARCHAR2(200 CHAR) NOT NULL, description VARCHAR2(2000 CHAR),
 duration_minutes NUMBER(3) NOT NULL CHECK(duration_minutes BETWEEN 1 AND 240),
 kind VARCHAR2(20) NOT NULL CHECK(kind IN ('FULL_TEST','MINI_TEST','PRACTICE')),
 status VARCHAR2(12) DEFAULT 'DRAFT' NOT NULL CHECK(status IN ('DRAFT','PUBLISHED','ARCHIVED')),
 created_at TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
) TABLESPACE toeic_data;
CREATE TABLE toeic_exam_items (
 exam_id NUMBER(12) NOT NULL REFERENCES toeic_exams(exam_id) ON DELETE CASCADE,
 question_id NUMBER(12) NOT NULL REFERENCES toeic_questions(question_id),
 position NUMBER(4) NOT NULL CHECK(position>0),
 PRIMARY KEY(exam_id,question_id), CONSTRAINT uq_toeic_position UNIQUE(exam_id,position)
) TABLESPACE toeic_data;
CREATE TABLE toeic_attempts (
 attempt_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 user_id NUMBER(12) NOT NULL REFERENCES toeic_users(user_id), exam_id NUMBER(12) NOT NULL REFERENCES toeic_exams(exam_id),
 status VARCHAR2(12) DEFAULT 'IN_PROGRESS' NOT NULL CHECK(status IN ('IN_PROGRESS','COMPLETED','EXPIRED')),
 started_at TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL, expires_at TIMESTAMP NOT NULL,
 submitted_at TIMESTAMP, listening_score NUMBER(3), reading_score NUMBER(3), correct_count NUMBER(4),
 total_count NUMBER(4) NOT NULL, elapsed_seconds NUMBER(6),
 CHECK(listening_score BETWEEN 0 AND 495), CHECK(reading_score BETWEEN 0 AND 495)
) TABLESPACE toeic_data;
CREATE UNIQUE INDEX uq_toeic_open_attempt ON toeic_attempts (
 CASE WHEN status='IN_PROGRESS' THEN user_id END, CASE WHEN status='IN_PROGRESS' THEN exam_id END
) TABLESPACE toeic_data;
CREATE TABLE toeic_answers (
 attempt_id NUMBER(12) NOT NULL REFERENCES toeic_attempts(attempt_id) ON DELETE CASCADE,
 question_id NUMBER(12) NOT NULL REFERENCES toeic_questions(question_id), position NUMBER(4) NOT NULL,
 part_no NUMBER(1) NOT NULL CHECK(part_no BETWEEN 1 AND 7), group_id NUMBER(12) NOT NULL,
 prompt CLOB NOT NULL, passage CLOB, choices_json CLOB NOT NULL CHECK(choices_json IS JSON),
 explanation CLOB, audio_url VARCHAR2(1000), image_url VARCHAR2(1000),
 correct_choice CHAR(1) NOT NULL, selected_choice CHAR(1) CHECK(selected_choice IN ('A','B','C','D')),
 marked NUMBER(1) DEFAULT 0 NOT NULL CHECK(marked IN (0,1)), is_correct NUMBER(1),
 PRIMARY KEY(attempt_id,question_id), UNIQUE(attempt_id,position)
) TABLESPACE toeic_data;
CREATE TABLE toeic_lessons (
 lesson_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 part_no NUMBER(1) CHECK(part_no BETWEEN 1 AND 7), title VARCHAR2(200 CHAR) NOT NULL,
 summary VARCHAR2(1000 CHAR), content CLOB NOT NULL, duration_minutes NUMBER(3) DEFAULT 10 NOT NULL CHECK(duration_minutes>0)
) TABLESPACE toeic_data;
CREATE TABLE toeic_vocabulary (
 word_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 word VARCHAR2(100) NOT NULL UNIQUE, pronunciation VARCHAR2(200), meaning VARCHAR2(500 CHAR) NOT NULL,
 example VARCHAR2(1000 CHAR), topic VARCHAR2(100 CHAR) NOT NULL
) TABLESPACE toeic_data;
CREATE TABLE toeic_saved_words (
 user_id NUMBER(12) NOT NULL REFERENCES toeic_users(user_id) ON DELETE CASCADE,
 word_id NUMBER(12) NOT NULL REFERENCES toeic_vocabulary(word_id) ON DELETE CASCADE,
 saved_at TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL, PRIMARY KEY(user_id,word_id)
) TABLESPACE toeic_data;
CREATE TABLE toeic_audit (
 audit_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 actor VARCHAR2(100), action VARCHAR2(30) NOT NULL, entity VARCHAR2(50) NOT NULL,
 entity_id NUMBER(12), detail VARCHAR2(1000 CHAR), created_at TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
) TABLESPACE toeic_data;
CREATE TABLE toeic_score_scale (
 section VARCHAR2(10) NOT NULL CHECK(section IN ('LISTENING','READING')),
 raw_score NUMBER(3) NOT NULL CHECK(raw_score BETWEEN 0 AND 100),
 scaled_score NUMBER(3) NOT NULL CHECK(scaled_score BETWEEN 5 AND 495), PRIMARY KEY(section,raw_score)
) TABLESPACE toeic_data;
CREATE INDEX ix_toeic_group ON toeic_questions(group_id) TABLESPACE toeic_data;
CREATE INDEX ix_toeic_exam_question ON toeic_exam_items(question_id) TABLESPACE toeic_data;
CREATE INDEX ix_toeic_user_attempt ON toeic_attempts(user_id,started_at) TABLESPACE toeic_data;
CREATE INDEX ix_toeic_exam_attempt ON toeic_attempts(exam_id) TABLESPACE toeic_data;
CREATE INDEX ix_toeic_answer_question ON toeic_answers(question_id) TABLESPACE toeic_data;
CREATE INDEX ix_toeic_users_role ON toeic_users(role_id) TABLESPACE toeic_data;
CREATE OR REPLACE VIEW vw_toeic_exam_summary AS
 SELECT e.exam_id,e.slug,e.title,e.description,e.duration_minutes,e.kind,e.status,
 COUNT(i.question_id) question_count,
 SUM(CASE WHEN g.part_no<=4 THEN 1 ELSE 0 END) listening_count,
 SUM(CASE WHEN g.part_no>=5 THEN 1 ELSE 0 END) reading_count
 FROM toeic_exams e LEFT JOIN toeic_exam_items i ON i.exam_id=e.exam_id
 LEFT JOIN toeic_questions q ON q.question_id=i.question_id LEFT JOIN toeic_groups g ON g.group_id=q.group_id
 GROUP BY e.exam_id,e.slug,e.title,e.description,e.duration_minutes,e.kind,e.status;
CREATE OR REPLACE VIEW vw_toeic_user_progress AS
 SELECT u.user_id,u.full_name,COUNT(a.attempt_id) completed_count,
 NVL(MAX(a.listening_score+a.reading_score),0) best_score,
 ROUND(AVG(a.listening_score+a.reading_score)) average_score
 FROM toeic_users u LEFT JOIN toeic_attempts a ON a.user_id=u.user_id AND a.status<>'IN_PROGRESS'
 GROUP BY u.user_id,u.full_name;
CREATE OR REPLACE TRIGGER trg_toeic_exam_audit
 AFTER INSERT OR UPDATE OR DELETE ON toeic_exams FOR EACH ROW
DECLARE v_action VARCHAR2(20);
BEGIN
 IF INSERTING THEN v_action:='CREATE'; ELSIF UPDATING THEN v_action:='UPDATE'; ELSE v_action:='DELETE'; END IF;
 INSERT INTO toeic_audit(actor,action,entity,entity_id,detail)
 VALUES(SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),v_action,'EXAM',NVL(:NEW.exam_id,:OLD.exam_id),NVL(:NEW.title,:OLD.title));
END;
/
CREATE OR REPLACE TRIGGER trg_toeic_question_audit
 AFTER INSERT OR UPDATE OR DELETE ON toeic_questions FOR EACH ROW
DECLARE v_action VARCHAR2(20);
BEGIN
 IF INSERTING THEN v_action:='CREATE'; ELSIF UPDATING THEN v_action:='UPDATE'; ELSE v_action:='DELETE'; END IF;
 INSERT INTO toeic_audit(actor,action,entity,entity_id) VALUES(SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),v_action,'QUESTION',NVL(:NEW.question_id,:OLD.question_id));
END;
/
COMMIT;
